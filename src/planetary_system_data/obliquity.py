# "Third Case: Planets Without Major Satellites"

# "A leftover oligarch, terrestrial planet, or failed core which has no major satellite will be most affected by its primary star.
# If a planet is in a spin-orbit resonance, its obliquity will be minimal. To determine its obliquity at random, assume a result of Minimal on the Obliquity Table, 
# and roll 3d6-8 (minimum 0) to find the exact value."

# "Otherwise, without the stabilizing presence of a major satellite, the planet’s obliquity is likely to change more drastically over time. Minor perturbations from 
# other planets in the system may lead to chaotic “excursions” of the rotation axis. For example, although at present the obliquity of Mars is about 25 degrees, 
# some models predict that Mars undergoes major excursions from about 0 degrees to as high as 60 degrees over millions of years."

# "To select a value for obliquity at random, begin by rolling 3d6:"
# "On a 7 or less, the planet’s obliquity has High Instability. Roll on the Obliquity Table with an additional -7 modifier."
# "On a 8-13, the planet’s obliquity is not currently unstable. Roll on the Obliquity Table normally."
# "On a 14 or higher, the planet’s obliquity has High Instability. Roll on the Obliquity Table with an additional +7 modifier."

# "Make a note of any result indicating High Instability. The planet’s rotational axis is likely to be changing its orientation frequently across million-year 
# timescales, and the result is likely to be drastic climate change."

# "Now make a roll on the Obliquity Table. Apply the same modifier that was computed during Step Nineteen for the Rotation Period Table, based on the degree of tidal 
# deceleration applied by the primary star (T times twelve, rounded to the nearest integer). Also apply any modifier (-7 or +7) due to High Instability. Refer to the 
# Obliquity Table, and possibly the Extreme Obliquity Table, as required to determine the planet's current obliquity"