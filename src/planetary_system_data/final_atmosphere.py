# Evaluating Human Breathability

# "For humans to comfortably breathe an atmosphere, it must meet all the following criteria:
# Molecular oxygen at a partial pressure of 0.120 to 0.300 atmospheres. Below this range, a respirator is required. Above the range, a filter or “reducing respirator” 
# will be needed. High levels of oxygen will also encourage widespread fires.
# Carbon dioxide at a partial pressure no higher than 0.015 atmospheres. Above this range, humans will suffer respiratory difficulties and may need a filter.
# Molecular nitrogen at a partial pressure no higher than about 4 atmospheres. Above this range, humans will suffer from nitrogen narcosis and eventually lose 
# consciousness. A filter or reducing respirator will be required.
# The other likely components of a Class 4 world’s atmosphere are unlikely to have any toxic or suffocating effect, so long as the above criteria are all met."

