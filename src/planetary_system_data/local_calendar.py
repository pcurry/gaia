# Length of Local Day for a Planet

# "To determine the length of a planet’s day—the planet’s rotation period with respect to its primary star rather than with 
# respect to the distant stars—compute 
# the following:"

# codify equation on page 95

# "T is the apparent length of the planet’s day in hours, P is the planet’s orbital period in hours as determined in Step 
# Eighteen, while R is the planet’s rotational period in hours as determined in Step Nineteen."

# "This equation is undefined in cases when the orbital period and rotational period are equal (that is, the planet is 
# tide-locked or in a spin-orbital resonance of 1:1). In this case, the length of the local day is effectively infinite—
# the sun never moves far in the sky!"

# "At the other extreme, if the orbital period is much longer than the rotational period, then the day length and the 
# rotational period will be very close together. To determine the length of the local year in local days, simply divide the 
# planet’s orbital period by the length of the local day as computed above."

# "Length of Apparent Orbital Period for a Satellite"

# "To determine the length of a satellite’s apparent orbital period, from any position on the planet’s surface, use the same 
# equation:"

# codify equation on page 95

# "In this case, T is the apparent length of the satellite’s orbital period in hours, P is the satellite’s actual orbital 
# period in hours as determined in Step Eighteen, while R is the planet’s rotational period in hours as determined in Step 
# Nineteen."

# "Again, this equation is undefined in cases when the satellite’s orbital period and the planet’s rotational period are equal 
# (that is, the planet is tide-locked to its satellite, or the satellite happens to orbit at a geosynchronous distance). In 
# this case, the length of the satellite’s apparent orbital period is effectively infinite—the satellite never moves in the 
# sky."

# "At the other extreme, if the satellite’s orbital period is much longer than the planet’s rotationalvperiod, then the 
# apparent orbital period and the rotational period will be very close together. Earth’s moon is a familiar example—its 
# apparent motion in the sky is dominated by Earth’s rotation."

# "It’s possible for a satellite’s orbital period to be shorter than the planet’s rotational period. For example, a 
# close-orbiting moonlet is likely to fall into this case. The apparent orbital period will therefore be negative, indicating 
# that the satellite appears to move backward over time. The satellite will rise in the west and set in the east."

