# this sub-program covers step 29 ("Presence of Life") from Zeigler, 2024 - "Architect of Worlds: Comprehensive World Design for Interstellar Fiction"
# starting from page 114

# "This step determines whether the world has native life, the nature of that life, and how complex it has become at the present time. The evolution of complex life forms takes time, and it also requires 
# that local conditions be congenial. The process estimates the amount of time it requires for seven specific evolutionary steps to take place, affected by the world’s other properties, sketching out the 
# world’s evolutionary history."

# Procedure

# "Begin by noting the current age of the star system, as established in Step Four. For any of the seven following events, if the total time to the event is greater than the star system’s age, then
# that event has not yet taken place on the world under development. Any further events that depend upon that one can be ignored."

# Abiogenesis (Deep Hydrothermal Vents)

# "If all the following conditions are true for the world under development:"
# World has not had a runaway greenhouse (dry or wet)
# Moderate, Extensive, or Massive prevalence of water
# Lithosphere is Soft, Early Plate, Mature Plate, or Ancient Plate
# World does not have Fixed Plate Tectonics

# "Then roll 3d6, multiply by 30 million years, and make a note of the result as the time to life near hydrothermal vents. If the age of the star system is greater than this, then the world has native life 
# which derives energy and nutrients from volcanic vents at the bottom of its oceans. The world does not require exposed liquid-water oceans for this form of life to appear. For example, there is speculation 
# that life may exist on some of the icy moons of the outer solar system, in large liquid-water oceans beneath each icy surface."

# Abiogenesis (Surface Refugia)

# "If all the following conditions are true for the world under development:"

# World is Class 4
# World has an active carbonate-silicate cycle
# Lithosphere is Soft, Early Plate, Mature Plate, or Ancient Plate

# "Then roll 3d6. Multiply the result by 100 million years if the world has a Soft Lithosphere or it has Mobile Plate Tectonics, or by 200 million years otherwise, and make a note of the result.
# If the same conditions hold and the world has undergone deep abiogenesis (see above), roll 3d6, multiply by 75 million years, add the time to deep abiogenesis, and make a note of that
# result as well."

# "Take the lesser of these two times and make note of it as the time to life in surface refugia. If the age of the star system is greater than this, then the world has native life which derives
# energy and nutrients from sources in shallow water or on exposed land. Very early on, this life will require special conditions that sometimes occur in shallow oceans, on beaches, or in
# fresh-water ponds. These refugia form the basis for all later expansion of life across a world’s surface."

# Special Case: Lifeless Worlds

# "All the following evolutionary events are dependent on the presence of life in either the deep oceans or in surface refugia. If a world doesn’t meet the criteria for either of the above events,
# then it will be barren and effectively lifeless. It’s possible that some hardy form of bacterial life clings to existence, but it will be difficult to detect and will have no significant effect on the
# world’s environment. In this case, skip forward to Step Thirty."

# Multicellular Life

# "If the world has undergone either form of abiogenesis (see above), then roll 3d6, multiply by 75 million years, and then add the time to abiogenesis (deep hydrothermal vents) or the time
# to abiogenesis (surface refugia), whichever is less. Make a note of the result as the time to multicellular life."

# "If the age of the star system is greater than this, then the world's native life has formed multicellular organisms. These organisms will be simple and primitive for a long time, but
# they'll form the basis for complex ecosystems based on plant and animal life."

# Photosynthesis

# "Photosynthesis is critical to the development of a complex surface ecology for a world, such as exists on Earth. Early forms of photosynthesis are likely to appear soon after the development
# of surface refugia. However, the form of photosynthesis with which we are most familiar the oxygenic photosynthesis that releases free oxygen as a by-product—takes much longer to
# evolve."

# "In any case, the difficulty of developing photosynthesis is strongly dependent on the color of light that a world receives from its primary star"

# "Stars like Sol produce most of their radiation in the visible-light range, which passes easily through the transparent atmosphere of an Earth-like world. Smaller and cooler stars (K-class and
# especially M-class) produce more of their radiation in the infrared bands, which have more trouble penetrating an atmosphere. Furthermore, the chemical pathways involved in photosynthesis are most 
# effective at certain visible light wavelengths. A world with a small, cool primary star receives less such light, and may take much longer to develop photosynthetic life."

# "If the world has life in surface refugia (see above), and its primary star is not a brown dwarf, then refer to the Photosynthesis Table."

# Codify the Photosynthesis Table on page 115

# Roll 3d6, multiply by the Photosynthesis Development Timescale entry for the spectral type of the world’s primary star, and then add the time to life in surface refugia. Make a note of the result as the 
# time to photosynthesis."

# "If the age of the star system is greater than this, then the world’s native life has developed the ability to synthesize food by using sunlight to drive the necessary chemical reactions, releasing
# oxygen as a byproduct. Organisms which develop this trait will establish all the world’s families of plant life."

# "Oxygen Catastrophe

# Although the development of oxygenic photosynthesis opens many new opportunities for a world’s ecology, it can also be catastrophic for existing life, which arose in its absence. Such
# anaerobic life finds oxygen as poisonous as we would find other oxidizing agents, such as chlorine or fluorine. The transition to new forms of life after the appearance of free oxygen is
# sometimes called the Oxygen Catastrophe."

# "After oxygenic photosynthesis develops, oxygen will be released by photosynthetic organisms, but at first that oxygen will tend to be dissolved in the oceans, or it will combine with exposed
# materials on land. It may take a long time for photosynthesis to build up significant free oxygen in a world’s atmosphere."

# "If a world has developed photosynthesis (see above), roll 3d6, multiply by 1.5 and by the appropriate entry in the Photosynthesis Table, and then add the time to photosynthesis. Make
# a note of the result as the time to the Oxygen Catastrophe."

# "If the age of the star system is greater than this, then the world’s oceans, land surfaces, and atmosphere have all become saturated with free oxygen and oxygen compounds. Many earlier
# forms of anaerobic life will likely have been driven into extinction, but new aerobic forms will have arisen which can tolerate or even take advantage of the available oxygen."

# "Another consequence of the Oxygen Catastrophe is the appearance of ozone (O3) in the upper atmosphere. Ozone is important because even trace amounts of it help to filter out short-
# wavelength light (ultraviolet and X-rays) from the primary star that would otherwise be deadly to biological life. Any world lacking atmospheric ozone is likely to be a dangerous place to
# visit, let alone live. Any life on such a world may be restricted to the oceans, or it may exhibit elaborate adaptations to protect itself from the primary star’s radiation."

# "Once the Oxygen Catastrophe has happened, life will be free to emerge from the oceans onto whatever dry land exists."

# Animal Life

# "Although multicellular life may appear quite early in a world’s history, the development of animals—complex multicellular organisms that are mobile and survive by eating organic
# matter—may take a long time. The appearance of free oxygen in the environment can promote the development of animals, but it is theoretically possible for anaerobic animals to evolve as
# well."

# "If a world has developed multicellular life (see above), roll 3d6, multiply by 300 million years, and then add the time to multicellular life. If the result is longer than the time to the Oxygen
# Catastrophe, then subtract half of the difference. Make a note of the result as the time to animal life."

# "If the age of the star system is greater than this, then the world will have given rise to animal life. Equivalents on Earth would be life forms that first appeared late in the Precambrian
# period, leading up through the so-called Cambrian Explosion about 540 million years ago. These ancestral forms eventually gave rise to all the animal phyla that exist today."

# Pre-Sapient Life

# "The earliest animals are driven purely by biological programming: the tropisms and instincts that they evolve to govern their behavior. Eventually, however, animal life will develop more
# elaborate systems for gathering and processing sensory data. Some animal species will even develop the first potential for self-aware, tool- and language-using minds. We will use the term
# pre-sapient for such species"

# "If a world has developed animal life (see above), roll 3d6. Multiply the result by 100 million years if the world has Massive prevalence of water, or by 50 million years otherwise. Add the
# time to animal life. Make a note of the result as the time to pre-sapient life."

# "If the age of the star system is greater than this, then the world will have given rise to one or more classes of animal life that have advanced nervous systems and may be capable of complex
# learned behavior. Equivalents on Earth would be the behaviorally complex animals that first appeared late in the Triassic period, about 300 million years ago."

# "The occurrence of sentient life, capable of language, tool use, and advanced technology, is beyond the scope of this book. At present we lack enough data to even guess at how often such
# life appears in the universe, although all the available evidence suggests it must be rare..."

# Atmospheric Free Oxygen

# "Before proceeding to the next step, estimate the prevalence of molecular oxygen in the atmosphere of the world under development."

# "If the world has photosynthetic life, but has not gone through the Oxygen Catastrophe, then estimate the partial atmospheric mass of molecular oxygen by rolling 3d6 and multiplying by
# 0.002. Round the result to two significant figures."

# "If the world has gone through the Oxygen Catastrophe, then estimate the partial atmospheric mass of molecular oxygen by rolling 3d6+10, multiplying by 0.01, and then multiplying by the
# atmosphere retention factor. Round the result to two significant figures. In either case, the result will be the partial atmospheric mass of molecular oxygen. We will refer to this value 
# as MO2 in later steps."